#!/bin/sh
# Generates a C header holding the EFF large Diceware wordlist as a fixed-width table.
# Usage: gen-wordlist.sh <eff_large_wordlist.txt> <eff_large_wordlist.txt.sha256> <out.h>
#
# The input must match its pinned sha256 and be the canonical 6^5-line list: line i
# carries the dice code for i in base 6 (digits 1-6), then a tab, then a lowercase
# word (a-z, a few with hyphens), with words strictly ascending. Index i in the
# table is therefore the word for that dice roll.
set -eu

if [ $# -ne 3 ]; then
    echo "usage: $0 <wordlist.txt> <wordlist.txt.sha256> <out.h>" >&2
    exit 2
fi
in=$1
sumfile=$2
out=$3

if command -v sha256sum >/dev/null 2>&1; then
    actual=$(sha256sum "$in" | cut -d' ' -f1)
else
    actual=$(shasum -a 256 "$in" | cut -d' ' -f1)
fi
expected=$(cut -d' ' -f1 "$sumfile")
if [ "$actual" != "$expected" ]; then
    echo "$0: $in does not match $sumfile (expected $expected, got $actual)" >&2
    exit 1
fi

LC_ALL=C awk -F '\t' '
function die(msg) { printf "%s:%d: %s\n", FILENAME, NR, msg > "/dev/stderr"; failed = 1; exit 1 }
{
    if (NF != 2) die("expected <dice code><TAB><word>")
    n = NR - 1; code = ""
    for (k = 0; k < 5; k++) { code = (n % 6 + 1) code; n = int(n / 6) }
    if ($1 != code) die("dice code " $1 " out of order, expected " code)
    if ($2 !~ /^[a-z][a-z-]*$/) die("word \"" $2 "\" is not lowercase a-z with hyphens")
    if (NR > 1 && $2 <= prev) die("word \"" $2 "\" is not strictly after \"" prev "\"")
    prev = $2
    words[NR] = $2
    if (length($2) > longest) longest = length($2)
}
END {
    if (failed) exit 1
    if (NR != 7776) { printf "%s: expected 7776 words, found %d\n", FILENAME, NR > "/dev/stderr"; exit 1 }
    print "/* Generated by tools/gen-wordlist.sh from data/eff_large_wordlist.txt. Do not edit. */"
    print "/* EFF large wordlist, (c) Electronic Frontier Foundation, CC BY 3.0 US. */"
    print "#ifndef DWARE_WORDLIST_H"
    print "#define DWARE_WORDLIST_H"
    print ""
    printf "#define WORDLIST_COUNT %d\n", NR
    printf "#define WORDLIST_WIDTH %d /* longest word plus its NUL */\n", longest + 1
    print ""
    print "static const char wordlist[WORDLIST_COUNT][WORDLIST_WIDTH] = {"
    for (i = 1; i <= NR; i++) printf "    \"%s\",\n", words[i]
    print "};"
    print ""
    print "#endif"
}
' "$in" > "$out.tmp"
mv "$out.tmp" "$out"
